export function evalStatus(v: number, id: string): IndicatorStatus | null {
  const def = INDICATORS.find((ind) => ind.id === id)
  if (!def) return null
  if (def.isDanger(v)) return 'danger'
  if (def.isHealthy(v)) return 'healthy'
  return 'caution'
}
